#!/usr/bin/env node
// Embeds fonts/JetBrainsMono-Regular.woff2 as a base64 string module so the
// serverless function (api/svg.js) never touches the filesystem at request
// time and needs no bundler file-tracing config for a binary asset.
// Re-run this only if the font file changes.

const fs = require("fs");
const path = require("path");

const FONT_PATH = path.join(__dirname, "..", "fonts", "JetBrainsMono-Regular.woff2");
const OUT_PATH = path.join(__dirname, "..", "lib", "font-data.js");

const buf = fs.readFileSync(FONT_PATH);
const b64 = buf.toString("base64");

const out = `// AUTO-GENERATED by tools/embed-font.js from fonts/JetBrainsMono-Regular.woff2
// Do not edit by hand - re-run \`node tools/embed-font.js\` instead.
module.exports = "${b64}";
`;

fs.writeFileSync(OUT_PATH, out);
console.log(`Wrote ${OUT_PATH} (${(b64.length / 1024).toFixed(0)} KB base64, source ${(buf.length / 1024).toFixed(0)} KB)`);
